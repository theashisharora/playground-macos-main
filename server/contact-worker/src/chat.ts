export const DEFAULT_GEMINI_MODEL = "gemini-3.5-flash-lite";

export interface ChatDeps {
  usage?: ChatUsageLimiter;
  verifyBot?: (token: string, ip: string | null) => Promise<boolean>;
  generate?: (system: string, contents: GeminiContent[]) => Promise<GeminiOutcome>;
  now?: () => number;
}

export const isChatLive = (env: Env) => env.CHAT_MODE === "live";

/** Names of settings live chat still needs (never their values). */
export function missingChatConfig(env: Env): string[] {
  const required: (keyof Env)[] = [
    "ALLOWED_ORIGINS",
    "GEMINI_API_KEY",
    "CHAT_SESSION_SECRET",
    "TURNSTILE_SECRET_KEY",
    "CHAT_RATE_LIMITER_DO"
  ];
  const missing = required.filter((k) => !env[k]);
  if (env.CHAT_SESSION_SECRET && env.CHAT_SESSION_SECRET.length < 32)
    missing.push("CHAT_SESSION_SECRET (min 32 chars)" as keyof Env);
  return missing;
}

export const MOCK_REPLY =
  "Preview mode: Ash AI isn't connected to Gemini here, so this reply was not generated by AI. " +
  "Once it's live, I'll answer questions about Ashish's experience, projects, skills and education " +
  'using only his public portfolio. To reach Ashish now, tap "Contact Ashish".';

const FALLBACK_REPLY =
  "Sorry, I can't help with that. I can only answer questions about Ashish's experience, " +
  'projects, skills and education. To ask Ashish directly, tap "Contact Ashish".';

// Per-isolate pre-filter: sheds bursts before they reach the Durable Objects.
// Not global, so it is only a cheap first line; the DO limits are authoritative.
const newShed = () =>
  memoryRateLimiter(CHAT_RATE.burst.max * 2, CHAT_RATE.burst.windowMs);
let isolateShed = newShed();
// Mock / local dev only (no Durable Object bound).
let memoryUsage: ChatUsageLimiter | null = null;

export function selectChatUsage(env: Env): ChatUsageLimiter {
  const cap = Number(env.CHAT_DAILY_LIMIT);
  const globalDaily = Number.isInteger(cap) && cap > 0 ? cap : CHAT_RATE.globalDaily;
  const ns = env.CHAT_RATE_LIMITER_DO;
  if (ns)
    return chatUsageLimiter(
      (max, windowMs): RateLimiter => durableObjectRateLimiter(ns, max, windowMs),
      globalDaily
    );
  memoryUsage ??= chatUsageLimiter(
    (max, windowMs) => memoryRateLimiter(max, windowMs),
    globalDaily
  );
  return memoryUsage;
}

/**
 * Strips a visitor's own contact details (email addresses, phone numbers)
 * before their text is sent to Gemini. Ash AI never needs them;
 * visitors who want a reply use the Contact Ashish conversation instead.
 */
export function redactContactInfo(text: string): string {
  return text
    .replace(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, "[email removed]")
    .replace(/\+?\d[\d\s().-]{7,}\d/g, (m) =>
      (m.match(/\d/g) ?? []).length >= 10 ? "[phone removed]" : m
    );
}

/** Cleans a model reply: plain text, bounded length, no contact details. */
export function sanitizeReply(text: string): string {
  let out = normalizeChatText(text)
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/^#{1,6}\s+/gm, "")
    .replace(/^\s*\*\s+/gm, "- ")
    // Never pass on an email address or phone number, whatever the model says.
    .replace(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, '(use "Contact Ashish")')
    .replace(/\+?\d[\d\s().-]{7,}\d/g, (m) =>
      (m.match(/\d/g) ?? []).length >= 10 ? "(not shared)" : m
    );
  if (chatLength(out) > CHAT_LIMITS.replyMax)
    out = `${Array.from(out)
      .slice(0, CHAT_LIMITS.replyMax - 1)
      .join("")
      .trimEnd()}…`;
  return out;
}

type Parsed =
  | {
      ok: true;
      message: string;
      history: ChatTurn[];
      session?: string;
      turnstileToken: string;
    }
  | { ok: false; error: string };

function parseChatBody(body: Record<string, unknown>): Parsed {
  if (typeof body.message !== "string") return { ok: false, error: "invalid" };
  const message = normalizeChatText(body.message);
  if (!message || chatLength(message) > CHAT_LIMITS.messageMax)
    return { ok: false, error: "invalid" };

  const rawHistory = body.history ?? [];
  if (!Array.isArray(rawHistory) || rawHistory.length > CHAT_LIMITS.historyMax)
    return { ok: false, error: "invalid_history" };
  const history: ChatTurn[] = [];
  for (const t of rawHistory) {
    if (!t || typeof t !== "object") return { ok: false, error: "invalid_history" };
    const { role, text, sig } = t as Record<string, unknown>;
    if ((role !== "user" && role !== "assistant") || typeof text !== "string")
      return { ok: false, error: "invalid_history" };
    const max = role === "user" ? CHAT_LIMITS.messageMax : CHAT_LIMITS.replyMax;
    if (!text.trim() || chatLength(text) > max)
      return { ok: false, error: "invalid_history" };
    if (
      role === "assistant" &&
      (typeof sig !== "string" || sig.length > CHAT_LIMITS.tokenMax)
    )
      return { ok: false, error: "invalid_history" };
    history.push(
      role === "assistant" ? { role, text, sig: sig as string } : { role, text }
    );
  }

  const session =
    typeof body.session === "string" && body.session.length <= CHAT_LIMITS.tokenMax
      ? body.session
      : undefined;
  const turnstileToken =
    typeof body.turnstileToken === "string" ? body.turnstileToken : "";
  return { ok: true, message, history, session, turnstileToken };
}

export async function handleChat(
  body: Record<string, unknown>,
  ip: string | null,
  env: Env,
  cors: Record<string, string>,
  deps: ChatDeps = {}
): Promise<Response> {
  const live = isChatLive(env);
  const now = deps.now ?? Date.now;

  if (live && missingChatConfig(env).length > 0) {
    console.error("Ash AI misconfigured; missing:", missingChatConfig(env).join(", "));
    return json(503, { ok: false, error: "not_configured" }, cors);
  }

  const parsed = parseChatBody(body);
  if (!parsed.ok) return json(400, { ok: false, error: parsed.error }, cors);

  // ---- Bot protection: a valid session, or a fresh Turnstile token ----
  const secret = env.CHAT_SESSION_SECRET ?? "";
  let session: { token: string; expiresAt: number } | undefined;
  if (live || deps.verifyBot) {
    const claims = live ? await readSession(secret, parsed.session, now()) : null;
    if (!claims) {
      if (!parsed.turnstileToken)
        return json(401, { ok: false, error: "session_required" }, cors);
      const verify =
        deps.verifyBot ??
        ((t: string, remoteIp: string | null) =>
          verifyTurnstile(t, env.TURNSTILE_SECRET_KEY as string, remoteIp));
      if (!(await verify(parsed.turnstileToken, ip)))
        return json(400, { ok: false, error: "bot_check_failed" }, cors);
      if (live) session = await issueSession(secret, now());
    }
  }

  // ---- History integrity: assistant turns must carry our signature ----
  if (live) {
    for (const t of parsed.history)
      if (t.role === "assistant" && !(await verifyReply(secret, t.text, t.sig ?? "")))
        return json(400, { ok: false, error: "invalid_history" }, cors);
  }

  // ---- Usage limits (separate from contact), fail closed ----
  const ipKey = ip ?? "unknown";
  if (!(await isolateShed.allow(`chat:${ipKey}`)))
    return json(
      429,
      { ok: false, error: "rate_limited" },
      { ...cors, "Retry-After": "600" }
    );
  let verdict;
  try {
    verdict = await (deps.usage ?? selectChatUsage(env)).consume(ipKey);
  } catch (err) {
    console.error("Chat limiter unavailable; rejecting request", err);
    return json(
      503,
      { ok: false, error: "temporarily_unavailable" },
      { ...cors, "Retry-After": "60" }
    );
  }
  if (verdict === "ip_limited")
    return json(
      429,
      { ok: false, error: "rate_limited" },
      { ...cors, "Retry-After": "600" }
    );
  if (verdict === "global_limited")
    return json(
      503,
      { ok: false, error: "daily_limit_reached" },
      { ...cors, "Retry-After": "3600" }
    );

  const extra = session
    ? { session: session.token, sessionExpiresAt: session.expiresAt }
    : {};

  if (!live) {
    // Honest preview: no model call, clearly labelled, never signed as AI output.
    return json(200, { ok: true, mode: "mock", reply: MOCK_REPLY, sig: "" }, cors);
  }

  // ---- Model call: facts in the system instruction, visitor text only as content ----
  const contents: GeminiContent[] = [];
  for (const t of parsed.history.slice(-CHAT_LIMITS.historyMax)) {
    const role = t.role === "assistant" ? "model" : "user";
    if (contents.length === 0 && role === "model") continue; // must start with the visitor
    const text = normalizeChatText(t.text);
    contents.push({
      role,
      parts: [{ text: role === "user" ? redactContactInfo(text) : text }]
    });
  }
  contents.push({ role: "user", parts: [{ text: redactContactInfo(parsed.message) }] });

  const generate =
    deps.generate ??
    ((system: string, c: GeminiContent[]) =>
      generateReply(
        {
          apiKey: env.GEMINI_API_KEY as string,
          model: env.GEMINI_MODEL || DEFAULT_GEMINI_MODEL
        },
        system,
        c
      ));
  const outcome = await generate(buildSystemInstruction(), contents);

  let reply: string;
  if (outcome.ok) reply = sanitizeReply(outcome.text);
  else if (outcome.reason === "blocked") reply = FALLBACK_REPLY;
  else if (outcome.reason === "rate_limited")
    return json(
      503,
      { ok: false, error: "ai_busy", ...extra },
      { ...cors, "Retry-After": "60" }
    );
  else return json(502, { ok: false, error: "ai_failed", ...extra }, cors);
  if (!reply) return json(502, { ok: false, error: "ai_failed", ...extra }, cors);

  return json(
    200,
    { ok: true, mode: "live", reply, sig: await signReply(secret, reply), ...extra },
    cors
  );
}

