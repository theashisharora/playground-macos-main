/**
 * Browser-side transport for "Ash AI". Talks to the same Worker as the
 * contact form (POST /chat). The Gemini key and the signing secret stay in the
 * Worker; the browser only holds the short-lived session it is given, in memory.
 */
import type { ChatTurn } from "~/shared/chatProtocol";
import { CONTACT_ENDPOINT } from "~/services/contact";

export type ChatResult =
  | { status: "ok"; reply: string; sig: string; mode: "live" | "mock"; session?: string }
  /** No backend in this build: nothing left the browser. */
  | { status: "preview"; reply: string }
  | {
      status: "error";
      code: string;
      message: string;
      /** Returned even on errors so a retry needn't repeat the bot check. */
      session?: string;
    };

export const chatConfigured = CONTACT_ENDPOINT !== "";

export const PREVIEW_REPLY =
  "Preview mode: Ash AI isn't connected in this build, so this reply was not generated by AI and your question wasn't sent anywhere. " +
  "Once it's live, I'll answer questions using only Ashish's public portfolio. To reach Ashish, tap \"Contact Ashish\".";

const ERROR_TEXT: Record<string, string> = {
  rate_limited:
    "You've asked a lot of questions in a short time. Please wait a few minutes.",
  daily_limit_reached:
    "Ash AI has reached its daily limit. Please try again tomorrow, or contact Ashish directly.",
  ai_busy: "Ash AI is busy right now. Please try again in a minute.",
  ai_failed: "Ash AI couldn't answer just now. Please try again.",
  temporarily_unavailable:
    "Ash AI is temporarily unavailable. Please try again in a minute.",
  not_configured:
    "Ash AI isn't available right now. You can still contact Ashish directly.",
  bot_check_failed: "The verification didn't pass. Please complete it again and retry.",
  session_required: "Please complete the verification below, then try again.",
  invalid_history:
    "This conversation couldn't be continued. Please start a new question.",
  invalid: "Please enter a shorter question.",
  origin_not_allowed: "Ash AI isn't available from this site address."
};

interface ChatOptions {
  endpoint?: string;
  fetchImpl?: typeof fetch;
  timeoutMs?: number;
  previewDelayMs?: number;
}

export async function sendChatMessage(
  req: {
    message: string;
    history: ChatTurn[];
    session?: string;
    turnstileToken?: string;
  },
  {
    endpoint = CONTACT_ENDPOINT,
    fetchImpl = fetch,
    timeoutMs = 25_000,
    previewDelayMs = 600
  }: ChatOptions = {}
): Promise<ChatResult> {
  if (!endpoint) {
    await new Promise((r) => setTimeout(r, previewDelayMs));
    return { status: "preview", reply: PREVIEW_REPLY };
  }
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const res = await fetchImpl(`${endpoint.replace(/\/$/, "")}/chat`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(req),
      signal: controller.signal
    });
    const data = (await res.json().catch(() => ({}))) as {
      ok?: boolean;
      mode?: string;
      reply?: string;
      sig?: string;
      session?: string;
      error?: string;
    };
    if (res.ok && data.ok === true && typeof data.reply === "string") {
      return {
        status: "ok",
        reply: data.reply,
        sig: data.sig ?? "",
        mode: data.mode === "live" ? "live" : "mock",
        session: data.session
      };
    }
    const code = data.error ?? "unknown";
    return {
      status: "error",
      code,
      message: ERROR_TEXT[code] ?? "Something went wrong. Please try again.",
      session: data.session
    };
  } catch (err) {
    const aborted = err instanceof DOMException && err.name === "AbortError";
    return {
      status: "error",
      code: aborted ? "timeout" : "network",
      message: aborted
        ? "Ash AI took too long to answer. Please try again."
        : "Couldn't reach the server. Please check your connection and try again."
    };
  } finally {
    clearTimeout(timer);
  }
}
